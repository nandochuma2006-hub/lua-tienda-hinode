/** Productos parecidos: misma línea primero, luego misma categoría/género. */
export function getRelated(product, limit = 4) {
  const others = PRODUCTS.filter((p) => p.code !== product.code);
  const score = (p) =>
    (p.line === product.line ? 4 : 0) +
    (p.family && p.family === product.family ? 2 : 0) +
    (p.gender === product.gender ? 1 : 0) +
    (p.category === product.category ? 1 : 0);
  return others
    .map((p) => ({ p, s: score(p) }))
    .filter(({ s }) => s >= 2)
    .sort((a, b) => b.s - a.s)
    .slice(0, limit)
    .map(({ p }) => p);
}
